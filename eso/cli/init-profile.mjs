import fs from 'node:fs';
import path from 'node:path';

/**
 * Resolve existing ancestor realpath if target does not yet exist.
 * Traces symlinks so that even if the target does not exist,
 * symlinks along the path (e.g. symlink .harness) are resolved to their target.
 */
function resolveRealPathWithAncestors(targetPath, depth = 0) {
    if (depth > 40) {
        const err = new Error(`Too many symbolic links encountered resolving "${targetPath}"`);
        err.code = 'ELOOP';
        throw err;
    }

    let curr = path.resolve(targetPath);
    const segments = [];

    while (true) {
        try {
            const lstat = fs.lstatSync(curr);
            if (lstat.isSymbolicLink()) {
                const linkTarget = fs.readlinkSync(curr);
                const resolvedLink = path.isAbsolute(linkTarget)
                    ? linkTarget
                    : path.resolve(path.dirname(curr), linkTarget);
                const realLinkTarget = resolveRealPathWithAncestors(resolvedLink, depth + 1);
                return segments.length > 0 ? path.join(realLinkTarget, ...segments) : realLinkTarget;
            }
            const realCurr = fs.realpathSync(curr);
            return segments.length > 0 ? path.join(realCurr, ...segments) : realCurr;
        } catch (err) {
            if (err.code === 'ENOENT') {
                const parent = path.dirname(curr);
                if (parent === curr) {
                    return segments.length > 0 ? path.join(curr, ...segments) : curr;
                }
                segments.unshift(path.basename(curr));
                curr = parent;
            } else {
                throw err;
            }
        }
    }
}

/**
 * Validate that target path is strictly inside consumerRoot (Never write outside consumer directory).
 */
export function assertWithinConsumer(consumerRoot, targetPath) {
    if (!consumerRoot) {
        const err = new Error('UNKNOWN_CONSUMER: Missing consumer root path');
        err.code = 'UNKNOWN_CONSUMER';
        throw err;
    }

    let resolvedRoot;
    try {
        if (!fs.existsSync(consumerRoot)) {
            const err = new Error(`UNKNOWN_CONSUMER: Consumer directory does not exist: "${consumerRoot}"`);
            err.code = 'UNKNOWN_CONSUMER';
            throw err;
        }
        resolvedRoot = fs.realpathSync(consumerRoot);
        const stat = fs.statSync(resolvedRoot);
        if (!stat.isDirectory()) {
            const err = new Error(`UNKNOWN_CONSUMER: Consumer path is not a directory: "${consumerRoot}"`);
            err.code = 'UNKNOWN_CONSUMER';
            throw err;
        }
    } catch (err) {
        if (err.code === 'UNKNOWN_CONSUMER') {
            throw err;
        }
        const e = new Error(`UNKNOWN_CONSUMER: Consumer directory does not exist: "${consumerRoot}"`);
        e.code = 'UNKNOWN_CONSUMER';
        throw e;
    }

    const resolvedTarget = resolveRealPathWithAncestors(
        path.isAbsolute(targetPath) ? targetPath : path.resolve(resolvedRoot, targetPath)
    );

    const rel = path.relative(resolvedRoot, resolvedTarget);
    const isInside = (rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel))) &&
                     (resolvedTarget === resolvedRoot || resolvedTarget.startsWith(resolvedRoot + path.sep));

    if (!isInside) {
        const err = new Error(`ACCESS_DENIED: Target path "${resolvedTarget}" is outside consumer directory "${resolvedRoot}"`);
        err.code = 'OUTSIDE_CONSUMER';
        throw err;
    }
}

/**
 * Generate default configuration object for ESO v2 consumer.
 */
export function defaultEsoV2Config(projectId) {
    return {
        version: 1,
        project: projectId,
        id: projectId,
        eso: {
            version: '2.0.0',
            mode: 'observe',
        },
        created_at: new Date().toISOString(),
    };
}

/**
 * Generate default state object for ESO v2 consumer.
 */
export function defaultEsoV2State(projectId) {
    return {
        version: 1,
        status: 'initialized',
        project: projectId,
        initialized_at: new Date().toISOString(),
        last_run: null,
    };
}

/**
 * Generate default turn hook content for ESO v2 consumer.
 */
export function defaultEsoV2Hook(harnessEsoRoot) {
    const root = harnessEsoRoot || process.cwd();
    const bridgePath = path.join(root, 'eso/adapters/src/host-bridge.mjs');
    return `// ESO Host Turn Hook (auto-generated by ESO init profile)
import { recordTurnEvidence } from ${JSON.stringify(bridgePath)};

export async function onTurn(turnData, { db, project } = {}) {
    return recordTurnEvidence({
        db,
        project: project || turnData.project,
        turnId: turnData.turnId || turnData.id,
        actorRole: turnData.actorRole || 'peer-dev',
        actorStatus: turnData.actorStatus || 'FULL',
        level: turnData.level || 'sufficient',
        mode: turnData.mode || 'do',
        basis: turnData.basis || 'verified',
        ruleVersion: turnData.ruleVersion || '2.0.0',
        payload: turnData.payload || turnData,
    });
}
`;
}

/**
 * Build file plan for ESO v2 init profile.
 */
export function buildProfilePlan(consumerPath, { projectId = null } = {}) {
    if (!consumerPath || !fs.existsSync(consumerPath)) {
        const err = new Error(`UNKNOWN_CONSUMER: Consumer directory does not exist: "${consumerPath}"`);
        err.code = 'UNKNOWN_CONSUMER';
        throw err;
    }

    const root = path.resolve(consumerPath);
    const id = projectId || path.basename(root);

    const configPath = path.join(root, '.harness', 'config.json');
    const statePath = path.join(root, '.harness', 'state.json');
    const hookPath = path.join(root, '.harness', 'hook.mjs');
    const hooksTurnPath = path.join(root, '.harness', 'hooks', 'turn.mjs');

    assertWithinConsumer(root, configPath);
    assertWithinConsumer(root, statePath);
    assertWithinConsumer(root, hookPath);
    assertWithinConsumer(root, hooksTurnPath);

    const hookContent = defaultEsoV2Hook(process.cwd());

    return {
        root,
        projectId: id,
        files: [
            {
                relative: '.harness/config.json',
                path: configPath,
                content: JSON.stringify(defaultEsoV2Config(id), null, 2) + '\n',
                action: 'create',
            },
            {
                relative: '.harness/state.json',
                path: statePath,
                content: JSON.stringify(defaultEsoV2State(id), null, 2) + '\n',
                action: 'create',
            },
            {
                relative: '.harness/hook.mjs',
                path: hookPath,
                content: hookContent,
                action: 'create',
            },
            {
                relative: '.harness/hooks/turn.mjs',
                path: hooksTurnPath,
                content: hookContent,
                action: 'create',
            },
        ],
    };
}

/**
 * Perform init profile for ESO v2.
 *
 * Requirements:
 * - If `--dry-run` or `--plan` is passed: write 0 files to disk, report dry run file list.
 * - 2 repeated runs must report `changed: false` on the second run (idempotent).
 * - Never write outside the consumer directory.
 */
export function initProfileV2(consumerPath, opts = {}) {
    if (!consumerPath || !fs.existsSync(consumerPath)) {
        const err = new Error(`UNKNOWN_CONSUMER: Consumer directory does not exist: "${consumerPath}"`);
        err.code = 'UNKNOWN_CONSUMER';
        throw err;
    }

    const dryRun = opts.dryRun === true || opts.plan === true;
    const force = opts.force === true;
    const plan = buildProfilePlan(consumerPath, opts);

    const filesReport = [];
    let anyChanged = false;

    for (const f of plan.files) {
        assertWithinConsumer(plan.root, f.path);
        const exists = fs.existsSync(f.path);
        let existingContent = null;
        if (exists) {
            existingContent = fs.readFileSync(f.path, 'utf8');
        }

        let willWrite = !exists || force;
        if (exists && !force) {
            if (f.relative.endsWith('.json')) {
                try {
                    const prior = JSON.parse(existingContent);
                    const planned = JSON.parse(f.content);
                    const isSemanticallyEqual = (f.relative === '.harness/config.json')
                        ? (prior.version === planned.version && prior.project === planned.project && (!planned.id || prior.id === planned.id) && JSON.stringify(prior.eso) === JSON.stringify(planned.eso))
                        : (f.relative === '.harness/state.json')
                            ? (prior.version === planned.version && prior.status === planned.status && prior.project === planned.project)
                            : (existingContent === f.content);
                    if (isSemanticallyEqual) {
                        willWrite = false;
                    }
                } catch {
                    willWrite = existingContent !== f.content;
                }
            } else {
                if (existingContent === f.content) {
                    willWrite = false;
                }
            }
        }

        if (willWrite) {
            anyChanged = true;
        }

        filesReport.push({
            relative: f.relative,
            path: f.path,
            action: willWrite ? (exists ? 'update' : 'create') : 'unchanged',
            exists,
            changed: willWrite,
        });

        if (!dryRun && willWrite) {
            fs.mkdirSync(path.dirname(f.path), { recursive: true });
            assertWithinConsumer(plan.root, f.path);
            fs.writeFileSync(f.path, f.content, 'utf8');
        }
    }

    return {
        ok: true,
        dryRun,
        changed: anyChanged,
        root: plan.root,
        projectId: plan.projectId,
        files: filesReport,
    };
}
