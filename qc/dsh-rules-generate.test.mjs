import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

import { alwaysOnRules, demoteHeadings, renderRules, run, splitFrontmatter } from '../scripts/build-dsh-rules.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = 'AGENTS.local.md';

/**
 * DSH has no `rules/` loader: `@deepseek-ai/dsh-agent-instructions` joins the file names it already
 * knows onto each directory from the project root to the session cwd, and nothing else. `AGENTS.local.md`
 * is one of those default names, which is why the mirror needs no profile entry at all — a repository
 * that carries the file gets its rules, a repository that does not gets nothing.
 *
 * That isolation is only real while two things hold: the script mirrors exactly the `alwaysApply: true`
 * rules and no others, and it writes a file DSH already reads. These tests pin both, plus the guard
 * that keeps the generator from eating a hand-written `AGENTS.local.md` — the same file name people
 * use for a personal, uncommitted overlay.
 */

function fixture(files) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-rules-'));
    fs.mkdirSync(path.join(root, '.cursor/rules'), { recursive: true });
    for (const [name, content] of Object.entries(files)) {
        fs.writeFileSync(path.join(root, '.cursor/rules', name), content);
    }
    return root;
}

const ALWAYS = '---\ndescription: X rule\nlayer: core\nalwaysApply: true\nversion: "1.0.0"\n---\n# X\n\nBody line.\n';

test('splitFrontmatter separates the YAML block from the body', () => {
    const { data, body } = splitFrontmatter('---\ndescription: "x"\nalwaysApply: true\n---\n# Title\n\nText\n');
    assert.deepEqual(data, { description: 'x', alwaysApply: 'true' });
    assert.equal(body, '# Title\n\nText\n');
});

test('a rule file without frontmatter is body-only', () => {
    const { data, body } = splitFrontmatter('# Title\n');
    assert.deepEqual(data, {});
    assert.equal(body, '# Title\n');
});

test('only alwaysApply rules are mirrored, in file-name order', () => {
    const root = fixture({
        'b.always.mdc': '---\ndescription: B\nalwaysApply: true\n---\nB body\n',
        'a.glob.mdc': '---\ndescription: A\nalwaysApply: false\nglobs: packages/**\n---\nA body\n',
        'c.yes.mdc': '---\ndescription: C\nalwaysApply: yes\n---\nC body\n',
        'd.none.mdc': 'no frontmatter here\n',
    });
    const rules = alwaysOnRules(root);
    assert.deepEqual(rules.map((r) => r.name), ['b.always', 'c.yes']);
    assert.deepEqual(rules.map((r) => r.source), ['.cursor/rules/b.always.mdc', '.cursor/rules/c.yes.mdc']);
});

test('demoteHeadings nests a rule under the mirror heading and leaves fenced code alone', () => {
    const body = '# Title\n\n## Section\n\n```bash\n# not a heading\n## also not\n```\n\n##### Deep\n';
    assert.equal(
        demoteHeadings(body),
        '### Title\n\n#### Section\n\n```bash\n# not a heading\n## also not\n```\n\n###### Deep\n',
    );
});

test('render drops frontmatter, keeps the source path, and is byte-stable', () => {
    const root = fixture({ 'core.x.mdc': ALWAYS });
    const once = renderRules(root);
    assert.equal(once, renderRules(root), 'render must not depend on mtime or map order');
    assert.match(once, /^<!-- generated by `node scripts\/build-dsh-rules\.mjs`/);
    assert.match(once, /## core\.x\n\nsource: `\.cursor\/rules\/core\.x\.mdc`\ndescription: X rule\n/);
    assert.match(once, /### X\n\nBody line\./);
    const section = once.slice(once.indexOf('## core.x'));
    for (const leaked of ['alwaysApply', 'layer:', 'version:']) {
        assert.ok(!section.includes(leaked), `frontmatter key leaked into the rule body: ${leaked}`);
    }
});

test('a hand-written AGENTS.local.md is never overwritten by accident', () => {
    const root = fixture({ 'core.x.mdc': ALWAYS });
    const outPath = path.join(root, OUT_FILE);
    fs.writeFileSync(outPath, '# My personal overlay\n\nnotes I do not want deleted\n');

    assert.equal(run([], root), 1, 'write without --force must refuse a foreign file');
    assert.equal(fs.readFileSync(outPath, 'utf8'), '# My personal overlay\n\nnotes I do not want deleted\n');
    assert.equal(run(['--check'], root), 1, '--check must not report a foreign file as up to date');

    assert.equal(run(['--force'], root), 0);
    assert.match(fs.readFileSync(outPath, 'utf8'), /^<!-- generated by `node scripts\/build-dsh-rules\.mjs`/);
    assert.equal(run(['--check'], root), 0, 'a file this script wrote is up to date');
});

test('the committed mirror matches the current rules', () => {
    const committed = fs.readFileSync(path.join(ROOT, OUT_FILE), 'utf8');
    assert.equal(committed, renderRules(ROOT), `${OUT_FILE} is stale — run \`node scripts/build-dsh-rules.mjs\``);
});

test('the mirror plus AGENTS.md fits the registry instruction budget', () => {
    // DSH caps each instruction chain at `maxBytes` (the shipped row uses 65,536) and drops whole
    // broader files when it overflows, so an oversized mirror would silently stop applying.
    const mirror = fs.statSync(path.join(ROOT, OUT_FILE)).size;
    const agents = fs.statSync(path.join(ROOT, 'AGENTS.md')).size;
    assert.ok(mirror + agents <= 65536, `AGENTS.md ${agents} + mirror ${mirror} exceeds the 65,536-byte chain`);
});
