/**
 * DSH bridge bundle (RFC 18 M2).
 *
 * DSH has no command-hook mechanism of its own; it ships `@deepseek-ai/dsh-hooks-claude-code`, which
 * runs a Claude Code `hooks` config on its interception seams. harness-eso already writes that exact
 * config (`.claude/settings.json`), so the bridge is a **bundle**: a package whose `cordis.patch.yml`
 * inserts one row pointing the bridge at the file the consumer already has.
 *
 * Why generate it
 * ---------------
 * The patch is easy to get subtly wrong (a quoted `@scope`, an absolute `configPath` that only works
 * from one launch directory). Generating it from a validated object makes the mistake impossible, and
 * lets a test assert the exact bytes.
 */

import path from 'node:path';

export const BRIDGE_ROW_ID = 'harness-eso-hooks';
export const BRIDGE_PACKAGE = '@deepseek-ai/dsh-hooks-claude-code';

/**
 * The bridge package is not part of a DSH profile by default (checked on 0.2.1-rc.2: no
 * `@deepseek-ai/dsh-hooks-*` in `~/.dsh/profiles/node_modules`). A bundle that inserts the row but
 * does not declare the dependency produces a row the loader cannot resolve, so the manifest declares
 * it and the installer is what fetches it.
 */
export const BRIDGE_PACKAGE_RANGE = '^0.2.1';

/**
 * @param {{ configPath?: string, projectDir?: string, defaultTimeoutMs?: number }} [options]
 */
export function buildDshBridgePatch(options = {}) {
    const configPath = options.configPath ?? './.claude/settings.json';
    const projectDir = options.projectDir ?? '.';
    const defaultTimeoutMs = options.defaultTimeoutMs ?? 120_000;

    if (typeof configPath !== 'string' || !configPath.trim()) throw new Error('configPath must be a non-empty string');
    if (typeof projectDir !== 'string' || !projectDir.trim()) throw new Error('projectDir must be a non-empty string');

    /*
     * The bridge reads `config.configPath` verbatim with `readFileSync` when the plugin loads, so a
     * relative path is resolved against the **DSH process cwd** (the app), not the workspace and not
     * `projectDir`. A generated bundle therefore pins the path: resolve it against `projectDir` when
     * that is absolute, and leave an absolute path untouched. A relative path is kept only when there
     * is nothing to resolve against — every other case would be a hook config the bridge never finds.
     */
    const configPathOut =
        !path.isAbsolute(configPath) && projectDir !== '.' && path.isAbsolute(projectDir)
            ? path.join(projectDir, configPath)
            : configPath;
    if (!Number.isInteger(defaultTimeoutMs) || defaultTimeoutMs <= 0) throw new Error('defaultTimeoutMs must be a positive integer');

    return {
        rows: [
            {
                id: BRIDGE_ROW_ID,
                name: BRIDGE_PACKAGE,
                config: { configPath: configPathOut, projectDir, defaultTimeoutMs },
            },
        ],
    };
}

function yamlScalar(value) {
    if (typeof value === 'number') return String(value);
    const text = String(value);
    // Only YAML syntax needs quoting: `@scope`, a leading indicator, or `: `/` #` inside. A relative
    // path like `./.claude/settings.json` is a plain scalar and quoting it only obscures the diff.
    const needsQuote = /^[@:[\]{}*&!%#`>|"']/.test(text) || text.includes(': ') || text.includes(' #');
    return needsQuote ? `'${text.replace(/'/g, "''")}'` : text;
}

/** Render the loader patch DSH expects (`- insert: [...]`). Deterministic, so a test can pin it. */
export function renderCordisPatchYaml(patch = buildDshBridgePatch()) {
    const lines = ['# generated by harness-eso — dsh bridge', '- insert:'];
    for (const row of patch.rows) {
        lines.push(`    - id: ${yamlScalar(row.id)}`);
        lines.push(`      name: ${yamlScalar(row.name)}`);
        lines.push('      config:');
        for (const [key, value] of Object.entries(row.config ?? {})) {
            lines.push(`        ${key}: ${yamlScalar(value)}`);
        }
    }
    return `${lines.join('\n')}\n`;
}

/** The bundle manifest, kept in one place so the CLI and tests agree. */
export function buildDshBundleManifest(name = 'harness-eso-dsh-bundle') {
    return {
        name,
        version: '1.0.0',
        private: true,
        type: 'module',
        dependencies: { [BRIDGE_PACKAGE]: BRIDGE_PACKAGE_RANGE },
        dsh: { bundle: { patch: './cordis.patch.yml' } },
    };
}

export function renderBundleReadme({ configPath = './.claude/settings.json' } = {}) {
    return `# harness-eso — DSH bridge bundle

Installs the ESO hook bridge into the current DSH profile. It does not contain ESO itself: the
commands it points at are the ones harness-eso already provisioned in the consumer.

## Prerequisite

The consumer must have the Claude host tree, because the bridge reads a Claude Code hook config. A
consumer provisioned earlier only needs the tree added — do not re-run the whole profile flow:

\`\`\`bash
# already provisioned (has .harness/host-pack + another IDE tree)
harnessctl host-pack add-ide --profile claude-superset <consumer>

# fresh consumer
harnessctl init profile <consumer> --host-mode claude
\`\`\`

The bundle declares \`@deepseek-ai/dsh-hooks-claude-code\` as a dependency because a DSH profile does
not ship it; install it through DSH so the package is fetched into the profile.

## Install

\`\`\`bash
# from DSH: Plugins -> install a bundle, target = this directory
# or with the agent tool:
#   plugin_manager { action: "install_bundle", target: "<this directory>" }
\`\`\`

The patch inserts \`${BRIDGE_ROW_ID}\` pointing \`@deepseek-ai/dsh-hooks-claude-code\` at
\`${configPath}\`. Supported Claude events are the bridge's subset (SessionStart, UserPromptSubmit,
PreToolUse, PostToolUse, Stop, subagent); PreCompact and SessionEnd are not supported by the bridge.

## Verify

\`\`\`bash
harnessctl verify host <consumer> --require-native
\`\`\`

H0–H3 must pass; H4 stays \`skip\` until the Cordis plugin registers a native provider.
`;
}
