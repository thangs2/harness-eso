#!/usr/bin/env node
/**
 * Build the installable DSH plugin: one ESM file with zero external imports, plus the loader patch.
 *
 * Why a bundle and not a package with dependencies: a DSH profile resolves the row's package from its
 * own module graph. Anything the bundle depends on is installed into the profile — and if that
 * dependency is a package the app already ships, the profile gets a second instance. `dsh-tools`
 * exports its scheduler as `Symbol()`, so the second instance breaks every tool call (ATF-OPS-001).
 * A file that imports only `node:*` gives the package manager nothing to install, so the pathology
 * cannot recur regardless of how DSH resolves plugins later.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

import { externalImports } from './build-host-pack.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PKG = path.join(ROOT, 'packages/harness-eso-dsh');
const ENTRY = path.join(PKG, 'src/plugin.mjs');
const OUT_DIR = path.join(PKG, 'dist');
const OUTFILE = path.join(OUT_DIR, 'eso-plugin.mjs');
const PATCH_FILE = path.join(PKG, 'cordis.patch.yml');

/** The id a consumer sees in the loader, and the row this bundle inserts. */
export const ROW_ID = 'harness-eso';
/*
 * A relative `name` in an inserted row is anchored beside the patch file it came from (DSH loader
 * contract), so the row does not depend on the profile resolving this package by name — it is the
 * file next to `cordis.patch.yml`, which is the bundle itself.
 */
export const ROW_NAME = './dist/eso-plugin.mjs';

export function renderPatch() {
    return `# generated by harness-eso — do not edit by hand
# \`node scripts/build-dsh-plugin.mjs\` writes this file next to the bundle it describes.
- insert:
    - id: ${ROW_ID}
      name: '${ROW_NAME}'
      config: {}
`;
}

function sha256(buffer) {
    return createHash('sha256').update(buffer).digest('hex');
}

async function bundle() {
    fs.mkdirSync(OUT_DIR, { recursive: true });
    const proc = spawnSync('bun', ['build', ENTRY, '--target', 'node', '--outfile', OUTFILE, '--format', 'esm'], {
        encoding: 'utf8',
        cwd: ROOT,
    });
    if (proc.error) throw new Error(`bun build failed to start: ${proc.error.message}`);
    if (proc.status !== 0) throw new Error(`bun build failed (${proc.status}):\n${proc.stderr || proc.stdout}`);
    return OUTFILE;
}

/**
 * Build and write the three installable artifacts. Exported so a test can assert the contract without
 * shelling out to a second process.
 */
export async function buildDshPlugin() {
    const outfile = await bundle();
    const source = fs.readFileSync(outfile, 'utf8');

    const external = externalImports(source);
    if (external.length) {
        throw new Error(
            `plugin bundle has non-builtin imports (${external.join(', ')}) — installing it would pull ` +
                'packages into the DSH profile and can split Symbol identity (ATF-OPS-001)',
        );
    }

    fs.writeFileSync(PATCH_FILE, renderPatch(), 'utf8');

    const manifest = {
        name: ROW_NAME,
        rowId: ROW_ID,
        entry: 'eso-plugin.mjs',
        files: { 'eso-plugin.mjs': sha256(fs.readFileSync(outfile)), 'cordis.patch.yml': sha256(fs.readFileSync(PATCH_FILE)) },
        builtAt: new Date().toISOString(),
        externalImports: external,
    };
    fs.writeFileSync(path.join(OUT_DIR, 'build.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
    return { outfile, patchFile: PATCH_FILE, manifest, bytes: fs.statSync(outfile).size };
}

if (import.meta.main) {
    const { manifest, bytes } = await buildDshPlugin();
    const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
    console.log(`dsh plugin → ${OUT_DIR}`);
    console.log(`  ${manifest.entry}  ${kb(bytes)}  (0 external imports)`);
    console.log(`  cordis.patch.yml  row ${manifest.rowId} → ${manifest.name}`);
    console.log('install: DSH → Plugins → install a bundle → this package directory');
}
