#!/usr/bin/env node
import { spawnSync } from 'node:child_process';
import { existsSync, rmSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve, join, basename } from 'node:path';
import { createHash } from 'node:crypto';
import os from 'node:os';
import assert from 'node:assert/strict';

import { createDbAdapter } from '../eso/graph/src/db-adapter.mjs';
import {
    ensureEvidenceSchema,
    readTurnEvidence,
} from '../eso/adapters/src/host-bridge.mjs';

// ESO-371: the run used to delete the only copy of the evidence with the sandbox, so QC could never open the DB a
// PASS referred to. The evidence is now copied out first and the copy is re-read before the sandbox is removed.
// `--evidence-out <dir>` names the destination; the default is a sibling of the sandbox under the OS temp dir.
const argv = process.argv.slice(2);
let rawTarget = null;
let evidenceOutFlag = null;
for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--evidence-out') {
        evidenceOutFlag = argv[i + 1] ?? null;
        if (!evidenceOutFlag) {
            console.error('❌ --evidence-out needs a directory');
            process.exit(2);
        }
        i += 1;
    } else if (arg.startsWith('--evidence-out=')) {
        evidenceOutFlag = arg.slice('--evidence-out='.length) || null;
        if (!evidenceOutFlag) {
            console.error('❌ --evidence-out needs a directory');
            process.exit(2);
        }
    } else if (arg.startsWith('--')) {
        console.error(`❌ Unknown option: ${arg}`);
        process.exit(2);
    } else if (rawTarget === null) {
        rawTarget = arg;
    } else {
        console.error(`❌ Unexpected argument: ${arg}`);
        process.exit(2);
    }
}

const targetDir = resolve(rawTarget || join(os.tmpdir(), `eso-smoke-${Date.now()}`));
const rootDir = process.cwd();

// CRITICAL-1: Guard path BEFORE any rmSync or mutations
const tmpRoot = os.tmpdir();
const isInsideTmp = targetDir.startsWith('/tmp/') || targetDir.startsWith(tmpRoot);
const isForbiddenTarget = !isInsideTmp ||
    targetDir === '/' ||
    targetDir === rootDir ||
    targetDir.includes('x79') ||
    targetDir.includes('harness-eso');

if (isForbiddenTarget) {
    console.error(`❌ ACCESS_DENIED: Target directory "${targetDir}" must be strictly inside a temporary directory (/tmp)`);
    process.exit(2);
}

// The retained evidence must outlive the sandbox: a destination inside it would be deleted with it.
const evidenceDir = resolve(evidenceOutFlag || join(os.tmpdir(), 'eso-smoke-evidence', basename(targetDir)));
const isInside = (child, parent) => child === parent || child.startsWith(parent.endsWith('/') ? parent : `${parent}/`);

if (isInside(evidenceDir, targetDir)) {
    console.error(`❌ ACCESS_DENIED: Evidence directory "${evidenceDir}" must not be inside the sandbox "${targetDir}" — it is removed at the end of the run`);
    process.exit(2);
}

console.log(`[smoke-turn] Target consumer (guarded /tmp): ${targetDir}`);
console.log(`[smoke-turn] Evidence destination: ${evidenceDir}`);

// 0. Ensure clean initial state (ONLY after validation)
if (existsSync(targetDir)) {
    rmSync(targetDir, { recursive: true, force: true });
}
mkdirSync(targetDir, { recursive: true });

// 1. Provision: ghi config + hook thật
console.log(`[smoke-turn] Running provision for ${targetDir}...`);
const provResult = spawnSync(
    './provision.sh',
    [targetDir, '--eso-v2'],
    { cwd: rootDir, encoding: 'utf-8' }
);

if (provResult.status !== 0) {
    console.error('[smoke-turn] Provision failed:', provResult.stderr || provResult.stdout);
    process.exit(provResult.status || 1);
}

const configPath = join(targetDir, '.harness', 'config.json');
assert.equal(existsSync(configPath), true, 'config.json must exist after provision');

// CRITICAL-2: Verify real hook from provision (NO STUB CREATION)
const hookCandidate1 = join(targetDir, '.harness', 'hooks', 'turn.mjs');
const hookCandidate2 = join(targetDir, '.harness', 'hook.mjs');
const hookPath = existsSync(hookCandidate1) ? hookCandidate1 : (existsSync(hookCandidate2) ? hookCandidate2 : null);

assert.ok(hookPath, 'Real hook (.harness/hooks/turn.mjs or .harness/hook.mjs) must be generated by provision');

// 2. Smoke turn: execute via real hook
console.log(`[smoke-turn] Executing smoke turn via real hook: ${hookPath}...`);
const turnHook = await import(`file://${hookPath}`);
assert.equal(typeof turnHook.onTurn, 'function', 'Hook must export onTurn function');

const dbUrl = process.env.ESO_SMOKE_DB_URL || process.env.ESO_GRAPH_DB_URL || process.env.ESO_CTX_DB_URL;
if (!dbUrl) {
    console.error('[smoke-turn] PostgreSQL URL required: set ESO_SMOKE_DB_URL (D-93: no SQLite)');
    process.exit(2);
}
const db = createDbAdapter(dbUrl);
await ensureEvidenceSchema(db);

const smokeTurnId = 'smoke-turn-' + Date.now();
const projectName = basename(targetDir);

const smokeEvidence = await turnHook.onTurn({
    turnId: smokeTurnId,
    project: projectName,
    actorRole: 'peer-dev',
    actorStatus: 'FULL',
    level: 'sufficient',
    mode: 'do',
    basis: 'verified',
    ruleVersion: '2.0.0',
    payload: {
        command: 'bun test',
        result: 'PASS',
        timestamp: new Date().toISOString(),
    },
}, { db, project: projectName });

assert.equal(smokeEvidence.turn_id, smokeTurnId);
console.log(`[smoke-turn] Recorded turn evidence: ${smokeTurnId}`);

// 3. Replay: đọc lại
console.log(`[smoke-turn] Replaying turn evidence from database...`);
const replayed = await readTurnEvidence({
    db,
    project: projectName,
    turnId: smokeTurnId,
});

assert.ok(replayed, 'Replayed record must exist');
assert.equal(replayed.turn_id, smokeTurnId);
assert.equal(replayed.project, projectName);
assert.equal(replayed.actor_role, 'peer-dev');
assert.equal(replayed.actor_status, 'FULL');
assert.equal(replayed.level, 'sufficient');
assert.equal(replayed.mode, 'do');
assert.equal(replayed.basis, 'verified');
assert.equal(replayed.payload.command, 'bun test');
assert.equal(replayed.payload.result, 'PASS');

console.log(`[smoke-turn] Replay verified successfully!`);

// 4. Retain the evidence BEFORE the sandbox is removed (ESO-371). A PASS whose DB is deleted with the sandbox is
//    unreviewable; QC needs the row, not the claim that the row existed.
await db.close();
mkdirSync(evidenceDir, { recursive: true });

// Retain a JSON evidence record; no SQLite file is copied or opened (D-93).
const retainedPath = join(evidenceDir, 'eso-smoke-turn.json');
writeFileSync(retainedPath, JSON.stringify(replayed, null, 2));
const retainedBytes = readFileSync(retainedPath);
const dbSha256 = createHash('sha256').update(retainedBytes).digest('hex');
const retainedRecord = JSON.parse(retainedBytes.toString('utf8'));
assert.ok(retainedRecord, 'The retained evidence record must hold the smoke turn');
assert.equal(retainedRecord.turn_id, smokeTurnId);
assert.equal(retainedRecord.payload.command, 'bun test');
assert.equal(retainedRecord.payload.result, 'PASS');

const evidenceLog = [
    'ESO-371 smoke-turn evidence',
    '===========================',
    `timestamp: ${new Date().toISOString()}`,
    `cwd: ${rootDir}`,
    `sandbox (removed after retention): ${targetDir}`,
    `project: ${projectName}`,
    `turn_id: ${smokeTurnId}`,
    'actor_role: peer-dev; actor_status: FULL',
    'level: sufficient; mode: do; basis: verified; rule_version: 2.0.0',
    `payload: ${JSON.stringify(replayed.payload)}`,
    `db file: ${retainedDb}`,
    `db bytes: ${dbBytes.byteLength}`,
    `db sha256: ${dbSha256}`,
    'replay of the retained copy:',
    `  turn_id: ${retainedRecord.turn_id}`,
    `  project: ${retainedRecord.project}`,
    `  actor_role: ${retainedRecord.actor_role}; actor_status: ${retainedRecord.actor_status}`,
    `  level: ${retainedRecord.level}; mode: ${retainedRecord.mode}; basis: ${retainedRecord.basis}`,
    `  payload.command: ${retainedRecord.payload.command}; payload.result: ${retainedRecord.payload.result}`,
    '',
].join('\n');
const evidenceLogPath = join(evidenceDir, 'eso-smoke-turn.log');
writeFileSync(evidenceLogPath, evidenceLog);

console.log(`[smoke-turn] Evidence retained before cleanup: ${retainedDb} (sha256 ${dbSha256.slice(0, 12)}…)`);

// 5. Remove sạch — the sandbox only; the evidence above lives outside it.
console.log(`[smoke-turn] Removing sandbox cleanly...`);
rmSync(targetDir, { recursive: true, force: true });
assert.equal(existsSync(targetDir), false, 'targetDir must be completely removed');
assert.equal(existsSync(retainedDb), true, 'retained evidence DB must survive the sandbox removal');
assert.equal(existsSync(evidenceLogPath), true, 'retained evidence log must survive the sandbox removal');

console.log(`[smoke-turn] Evidence kept at: ${evidenceDir} (eso-smoke-turn.json + eso-smoke-turn.log)`);
console.log(`[smoke-turn] DoD VERIFIED: provision config+hook, smoke turn evidence_turn via real hook, replay, evidence retained, remove sạch!`);
process.exit(0);
